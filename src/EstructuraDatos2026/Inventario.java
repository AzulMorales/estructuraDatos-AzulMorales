    public void actualizarLista(){
       txtLista.setText("");
       listaTexto = "";
       for(Producto2 p:listaProductos){
           listaTexto+= p.getNombre() + " $" + p.getPrecio() +" (" + p.getStock()+ ") \n";
       }
       //reiniciar campos
       txtLista.setText(listaTexto);
       txtNombre.setText("");
       txtPrecio.setText("");
       txtMarca.setText("");
       txtStock.setText("");
       
       //focus en no,bre para volver a empezar
       txtNombre.requestFocusInWindow();
    }

