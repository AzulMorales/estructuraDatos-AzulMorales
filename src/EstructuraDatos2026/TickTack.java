    private boolean verificarGanador(){
        String a1 = txt1.getText(), a2 = txt2.getText(), a3 = txt3.getText();
        String b1 = txt4.getText(), b2 = txt5.getText(), b3 = txt6.getText();
        String c1 = txt7.getText(), c2 = txt8.getText(), c3 = txt9.getText();

        //combinaciones ganadoras
        return ( !a1.isEmpty() && a1.equals(a2) && a2.equals(a3) ) ||
               ( !b1.isEmpty() && b1.equals(b2) && b2.equals(b3) ) ||
               ( !c1.isEmpty() && c1.equals(c2) && c2.equals(c3) ) ||
               ( !a1.isEmpty() && a1.equals(b1) && b1.equals(c1) ) ||
               ( !a2.isEmpty() && a2.equals(b2) && b2.equals(c2) ) ||
               ( !a3.isEmpty() && a3.equals(b3) && b3.equals(c3) ) ||
               ( !a1.isEmpty() && a1.equals(b2) && b2.equals(c3) ) ||
               ( !a3.isEmpty() && a3.equals(b2) && c1.equals(c3) );
    }  
         
         
