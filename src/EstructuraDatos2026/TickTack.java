        for (JTextField tf : celdas) {
            tf.setEditable(false);
            // Evento de clic
            tf.addMouseListener(new java.awt.event.MouseAdapter() {
                public void mouseClicked(java.awt.event.MouseEvent evt) {
                    
                    if (juegoTerminado || !tf.getText().isEmpty()) return;
                    
                    tf.setText(turno);
                    if (turno.equals("X")) {
                        tf.setForeground(java.awt.Color.decode("#150745")); 
                    } else {
                        tf.setForeground(java.awt.Color.decode("#72AFFF")); 
                 }
                    
                    if (verificarGanador()) {
                        lblGano.setText(turno);
                        juegoTerminado = true;
                    } else {
                        // Cambiamos de turno
                        turno = turno.equals("X") ? "O" : "X";
                    }
                }
            });
    }
